#!/usr/bin/env node
/**
 * Generate src/client/super-agent-client.js from the vendored upstream client.
 *
 * Upstream ships lib/client.js as a self-executing bundle:
 *
 *   window.__ModuleLoader__.load({ id: 'dsh-super-agent', factory: (require) => {...} })
 *
 * The fused package serves ONE client.js, so the upstream factory body is
 * lifted into an importable function and invoked from the composite apply with
 * a require shim. The transform is two exact-string replacements; anything
 * else aborts the build so drift fails loud.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
// Normalize line endings first: a Windows checkout may carry CRLF, and the
// wrapper surgery below matches on exact LF sequences.
const source = readFileSync(join(root, 'super-agent', 'lib', 'client.js'), 'utf8').replace(/\r\n/g, '\n')

const HEAD = "window.__ModuleLoader__.load({\n  id: 'dsh-super-agent',\n  factory: (require) => {"
const HEAD_NEW =
  '/**\n * GENERATED by scripts/gen-super-agent-client.mjs — do not edit.\n' +
  ' * Source: super-agent/lib/client.js, with the ModuleLoader wrapper lifted\n' +
  ' * into an importable factory so the fused package can serve one client.js.\n */\n' +
  'export const superAgentClientFactory = (require) => {'
const TAIL = '    return module.exports\n  },\n})'
const TAIL_NEW = '    return module.exports\n}'

if (!source.includes(HEAD)) throw new Error('upstream client.js head does not match the expected wrapper')
if (!source.includes(TAIL)) throw new Error('upstream client.js tail does not match the expected wrapper')

const body = source.replace(HEAD, HEAD_NEW).replace(TAIL, TAIL_NEW)

const outFile = join(root, 'src', 'client', 'super-agent-client.js')
mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, body, 'utf8')

// Verify the generated module: import it, run the factory with a require shim,
// and check the exports the composite apply depends on.
const mod = await import(pathToFileURL(outFile).href)
const captured = { react: { createElement: () => null } }
const exports = mod.superAgentClientFactory((id) => {
  if (id === 'react') return captured.react
  throw new Error(`unexpected seed module: ${id}`)
})
if (typeof exports.apply !== 'function') throw new Error('generated factory lost `apply`')
if (!Array.isArray(exports.inject)) throw new Error('generated factory lost `inject`')
if (exports.PANEL_ID !== 'super-agent') throw new Error(`unexpected PANEL_ID: ${exports.PANEL_ID}`)
console.log(`[gen-super-agent-client] ok — inject=${JSON.stringify(exports.inject)} panel=${exports.PANEL_ID}`)
